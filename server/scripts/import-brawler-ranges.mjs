import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";

const root = path.resolve(import.meta.dirname, "../..");
const catalogFile = path.join(root, "client/src/data/rankedData.ts");
const sourceFile = "/home/ubuntu/upload/brawlstars-stats.azurewebsites.net_Brawlers_1786759491867.md";
const outputFile = path.join(root, "shared/brawlerAttackRanges.ts");
const reportFile = path.join(root, "reports/brawler-attack-range-import.json");
const sourceUrl = "https://brawlstars-stats.azurewebsites.net/Brawlers";
const openingRangeThreshold = 8;

function keyOf(value) {
  return value.toLowerCase().replace(/[^a-z0-9]/g, "");
}

function extractCatalogNames(source) {
  return [...new Set([...source.matchAll(/["']brawler["']\s*:\s*["']([^"']+)["']/g)].map((match) => match[1]))].sort((a, b) => a.localeCompare(b));
}

function extractRanges(markdown) {
  const sections = markdown.split(/(?=^\[[^\]]+ ## )/m);
  const ranges = new Map();

  for (const section of sections) {
    const name = section.match(/^\[([^\]]+?) ## /m)?.[1];
    const afterLabel = section.match(/\* Attack Range\s*\n([\s\S]*?)(?=\n\* (?:Attack Damage|Projectile Speed|Movement Speed|Max Health)|\n\[[^\]]+ ## |$)/m)?.[1];
    if (!name || !afterLabel) continue;

    const normalizedBlock = afterLabel.replace(/\\\./g, ".");
    const values = [...normalizedBlock.matchAll(/\d+(?:\.\d+)?/g)].map((match) => Number(match[0])).filter(Number.isFinite);
    if (values.length) ranges.set(keyOf(name), Math.max(...values));
  }

  return ranges;
}

const [catalogSource, statsSource] = await Promise.all([readFile(catalogFile, "utf8"), readFile(sourceFile, "utf8")]);
const catalogNames = extractCatalogNames(catalogSource);
const sourceRanges = extractRanges(statsSource);
const records = catalogNames.map((name) => ({
  brawler: name,
  mainAttackRange: sourceRanges.get(keyOf(name)) ?? null,
}));
const longRangeNames = records
  .filter((record) => (record.mainAttackRange ?? 0) >= openingRangeThreshold)
  .map((record) => record.brawler);
const missing = records.filter((record) => record.mainAttackRange === null).map((record) => record.brawler);

const generated = `/*\n * Auto-generated by server/scripts/import-brawler-ranges.mjs.\n * Primary source: ${sourceUrl}\n * Rule: the opening bonus applies only when main attack range is at least ${openingRangeThreshold} tiles.\n */\n\nexport const mainAttackRanges = ${JSON.stringify(Object.fromEntries(records.map((record) => [record.brawler, record.mainAttackRange])), null, 2)} as const;\n\nfunction rangeKey(value: string) {\n  return value.toLowerCase().replace(/[^a-z0-9]/g, "");\n}\n\nconst rangesByKey = new Map<string, number | null>(Object.entries(mainAttackRanges).map(([name, range]) => [rangeKey(name), range]));\n\nexport function getMainAttackRange(brawlerName: string) {\n  return rangesByKey.get(rangeKey(brawlerName)) ?? null;\n}\n\nexport const longRangeBrawlerNames = new Set<string>(${JSON.stringify(longRangeNames, null, 2)});\nconst longRangeKeys = new Set(Array.from(longRangeBrawlerNames, rangeKey));\n\nexport function hasLongRangeMainAttack(brawlerName: string) {\n  return longRangeKeys.has(rangeKey(brawlerName));\n}\n`;

await mkdir(path.dirname(reportFile), { recursive: true });
await Promise.all([
  writeFile(outputFile, generated, "utf8"),
  writeFile(reportFile, `${JSON.stringify({ sourceUrl, openingRangeThreshold, catalogCount: catalogNames.length, longRangeCount: longRangeNames.length, missing, records }, null, 2)}\n`, "utf8"),
]);

console.log(`Imported ranges for ${records.length} catalog brawlers; ${longRangeNames.length} reach at least ${openingRangeThreshold} tiles; ${missing.length} missing.`);
if (missing.length) console.log(`Missing: ${missing.join(", ")}`);
